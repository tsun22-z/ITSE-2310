#!/usr/bin/env swift

// Using Comparison Operators
//  Operators    Description
//  ==           Equal to
//  !=           Not Equal to 
//  >            Greater than
//  <            Less than
//  >=           Greater than or Equal to
//  <+           Less than or Equal to


// Comparison Operators
print(1 == 1)   // Equal to, true becuase 1 is Equal to 1

print(2 != 1)   // not Equal to, true becuase 2 is not Equal to 1

print(2 > 1)    // Greater than, true becuase 2 is Greater than 1

print(1 < 2)    // Less than, true becuase 1 is Less than 2

print(1 >= 1)   // Greater than or Equal to, true becuase 1 is Greater than or Equal to 1

print(2 <= 1)   // Less than or Equal to, false becuase 2 is Not Less than or Equal to 1
